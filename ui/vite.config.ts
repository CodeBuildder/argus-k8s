import { defineConfig } from 'vite'
import react from '@vitejs/plugin-react'

export default defineConfig({
  plugins: [react()],
  server: {
    port: 5173,
    proxy: {
      '/api': {
        // Uvicorn is deliberately bound to IPv4 by the cluster-free launcher.
        // Using `localhost` here can resolve to ::1 in Node and disconnect an
        // otherwise healthy backend.
        target: 'http://127.0.0.1:8000',
        changeOrigin: true,
        rewrite: (path) => path.replace(/^\/api/, ''),
      },
    },
  },
})
